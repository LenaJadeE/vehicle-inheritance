package com.pluralsight;

public class Hovercraft {

    private int numberOfJets;
    private String skirtColor;
    private boolean waterCapable;

    public int getNumberOfJets() {
        return numberOfJets;
    }

    public void setNumberOfJets(int numberOfJets) {
        this.numberOfJets = numberOfJets;
    }

    public String getSkirtColor() {
        return skirtColor;
    }

    public void setSkirtColor(String skirtColor) {
        this.skirtColor = skirtColor;
    }

    public boolean isWaterCapable() {
        return waterCapable;
    }

    public void setWaterCapable(boolean waterCapable) {
        this.waterCapable = waterCapable;
    }
}
